#!/usr/bin/env python3
"""
Generate Publication-Ready LaTeX, Markdown, and CSV Summary Tables from Benchmark Results.

Aggregates multi-seed experimental runs across:
- Primary Literature Baselines (Update-All, Random, Active Learning, Small-Loss, CoreSet, ALG)
- Component Ablations (w/o Reliability, w/o Novelty, w/o Uncertainty, Hard Binary Gate)
- Stream Conditions (Clean Stream, Standard Perturbation, Extreme Stress)

Usage:
    python scripts/generate_paper_tables.py [--input-dir results/experiments/paper_benchmark] [--output-dir research/tables]
"""

from __future__ import annotations

import argparse
import json
import logging
from collections import defaultdict
from pathlib import Path
from typing import Any

import numpy as np

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

METHOD_ORDER = [
    "update_all",
    "random",
    "uncertainty_only",
    "small_loss",
    "coreset",
    "gated_full",
]

ABLATION_ORDER = [
    "gated_full",
    "ablation_no_reliability",
    "ablation_no_novelty",
    "ablation_no_uncertainty",
    "ablation_no_defer",
]

METHOD_NAMES = {
    "update_all": "Conventional (Update-All)",
    "random": "Budget-Matched Random",
    "uncertainty_only": "Active Learning (Uncertainty-Only)",
    "small_loss": "Small-Loss (Co-Teaching / MentorNet)",
    "coreset": "Core-Set Diversity (Novelty-Only)",
    "gated_full": "\\textbf{Adaptive Learning Gate (ALG Ours)}",
    "ablation_no_reliability": "ALG w/o Reliability ($w_{\\text{unrel}}=0$)",
    "ablation_no_novelty": "ALG w/o Novelty ($w_{\\text{nov}}=0$)",
    "ablation_no_uncertainty": "ALG w/o Uncertainty ($w_{\\text{unc}}=0$)",
    "ablation_no_defer": "ALG w/o Deferral (Hard Binary Gate)",
}

PLAIN_NAMES = {
    "update_all": "Conventional (Update-All)",
    "random": "Budget-Matched Random",
    "uncertainty_only": "Active Learning (Uncertainty-Only)",
    "small_loss": "Small-Loss (Co-Teaching / MentorNet)",
    "coreset": "Core-Set Diversity (Novelty-Only)",
    "gated_full": "Adaptive Learning Gate (ALG Ours)",
    "ablation_no_reliability": "ALG w/o Reliability (w_unrel=0)",
    "ablation_no_novelty": "ALG w/o Novelty (w_nov=0)",
    "ablation_no_uncertainty": "ALG w/o Uncertainty (w_unc=0)",
    "ablation_no_defer": "ALG w/o Deferral (Hard Binary Gate)",
}


def load_results(input_dir: Path) -> dict[str, dict[str, list[dict[str, Any]]]]:
    """Group result files by condition and method."""
    grouped: dict[str, dict[str, list[dict[str, Any]]]] = defaultdict(lambda: defaultdict(list))
    for f in input_dir.glob("*.json"):
        if f.name.startswith("summary") or f.name.startswith("aggregated"):
            continue
        try:
            with open(f, "r", encoding="utf-8") as fp:
                data = json.load(fp)
                cond = data.get("condition")
                method = data.get("method")
                if cond and method:
                    grouped[cond][method].append(data)
        except Exception as e:
            logger.warning("Error reading %s: %e", f.name, e)
    return grouped


def aggregate_metric(runs: list[dict[str, Any]], key: str) -> tuple[float, float]:
    vals = [r[key] for r in runs if key in r]
    if not vals:
        return 0.0, 0.0
    return float(np.mean(vals)), float(np.std(vals))


def generate_latex_table1(grouped: dict[str, dict[str, list[dict[str, Any]]]], out_file: Path) -> None:
    """Generate Main Comparative Benchmark LaTeX Table."""
    conditions = ["clean_stream", "noisy_stream", "high_noise_stream"]
    
    tex = []
    tex.append("% Auto-generated by scripts/generate_paper_tables.py")
    tex.append("\\begin{table*}[t]")
    tex.append("\\centering")
    tex.append("\\small")
    tex.append("\\caption{\\textbf{Continual Streaming Adaptation Benchmark on CIFAR-10 (Pre-trained ResNet-56, 94.26\\% Initial Accuracy).} Performance across clean, standard perturbation (20\\% noise), and severe stress (40\\% noise) streams. Results reported as Mean $\\pm$ Std across random seeds.}")
    tex.append("\\label{tab:main_benchmark}")
    tex.append("\\begin{tabular}{l|cc|ccc|ccc}")
    tex.append("\\hline")
    tex.append("\\multirow{2}{*}{\\textbf{Method}} & \\multicolumn{2}{c|}{\\textbf{Clean Stream (0\\% Noise)}} & \\multicolumn{3}{c|}{\\textbf{Adversarial Perturbation (20\\% Noise)}} & \\multicolumn{3}{c}{\\textbf{Severe Stress (40\\% Noise)}} \\\\")
    tex.append(" & \\textbf{Acc (\\%)} & \\textbf{Comp. Saved} & \\textbf{Acc (\\%)} & \\textbf{Noise Blk (\\%)} & \\textbf{Comp. Saved} & \\textbf{Acc (\\%)} & \\textbf{Noise Blk (\\%)} & \\textbf{Comp. Saved} \\\\")
    tex.append("\\hline")

    for method in METHOD_ORDER:
        row_str = f"{METHOD_NAMES.get(method, method)}"
        for cond in conditions:
            runs = grouped.get(cond, {}).get(method, [])
            if not runs:
                # Fallback if condition not run yet
                if cond == "clean_stream":
                    row_str += " & -- & --"
                else:
                    row_str += " & -- & -- & --"
                continue
            
            acc_m, acc_s = aggregate_metric(runs, "final_test_accuracy")
            comp_m, comp_s = aggregate_metric(runs, "sample_savings_pct")
            noise_m, noise_s = aggregate_metric(runs, "noise_interception_pct")
            
            if cond == "clean_stream":
                row_str += f" & {acc_m:.2f} $\\pm$ {acc_s:.2f} & {comp_m:.1f}\\%"
            else:
                row_str += f" & {acc_m:.2f} $\\pm$ {acc_s:.2f} & {noise_m:.1f}\\% & {comp_m:.1f}\\%"
        row_str += " \\\\"
        tex.append(row_str)

    tex.append("\\hline")
    tex.append("\\end{tabular}")
    tex.append("\\end{table*}")

    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(tex))
    logger.info("Saved LaTeX Table 1 to %s", out_file)


def generate_latex_table2(grouped: dict[str, dict[str, list[dict[str, Any]]]], out_file: Path) -> None:
    """Generate Component Ablation Study LaTeX Table."""
    cond = "noisy_stream"
    runs_by_method = grouped.get(cond, {})

    tex = []
    tex.append("% Auto-generated by scripts/generate_paper_tables.py")
    tex.append("\\begin{table}[h]")
    tex.append("\\centering")
    tex.append("\\small")
    tex.append("\\caption{\\textbf{Component Ablation Study on Adversarially Perturbed Stream (20\\% Noise).} Demonstrates the vital contribution of each individual signal and the quarantine deferral mechanism.}")
    tex.append("\\label{tab:ablation_study}")
    tex.append("\\begin{tabular}{l|c|c|c}")
    tex.append("\\hline")
    tex.append("\\textbf{Configuration} & \\textbf{Test Acc (\\%)} & \\textbf{Noise Blocked (\\%)} & \\textbf{Compute Saved (\\%)} \\\\")
    tex.append("\\hline")

    for method in ABLATION_ORDER:
        runs = runs_by_method.get(method, [])
        if not runs:
            tex.append(f"{METHOD_NAMES.get(method, method)} & -- & -- & -- \\\\")
            continue
        acc_m, acc_s = aggregate_metric(runs, "final_test_accuracy")
        noise_m, noise_s = aggregate_metric(runs, "noise_interception_pct")
        comp_m, comp_s = aggregate_metric(runs, "sample_savings_pct")
        tex.append(f"{METHOD_NAMES.get(method, method)} & {acc_m:.2f} $\\pm$ {acc_s:.2f} & {noise_m:.1f}\\% & {comp_m:.1f}\\% \\\\")

    tex.append("\\hline")
    tex.append("\\end{tabular}")
    tex.append("\\end{table}")

    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(tex))
    logger.info("Saved LaTeX Table 2 to %s", out_file)


def generate_markdown_summary(grouped: dict[str, dict[str, list[dict[str, Any]]]], out_file: Path) -> None:
    """Generate Markdown and CSV tables."""
    lines = []
    lines.append("# Benchmark Empirical Results Summary\n")
    lines.append("| Condition | Method | Test Acc (%) | Noise Ingested | Noise Blocked (%) | Compute Saved (%) | Runtime (s) |")
    lines.append("|---|---|:---:|:---:|:---:|:---:|:---:|")

    for cond, methods in sorted(grouped.items()):
        for m, runs in sorted(methods.items()):
            acc_m, acc_s = aggregate_metric(runs, "final_test_accuracy")
            noise_m, _ = aggregate_metric(runs, "noise_interception_pct")
            comp_m, _ = aggregate_metric(runs, "sample_savings_pct")
            time_m, _ = aggregate_metric(runs, "elapsed_seconds")
            ing_m, _ = aggregate_metric(runs, "noise_ingested")
            tot_noisy = runs[0].get("total_noisy_labels", 0) if runs else 0

            lines.append(
                f"| `{cond}` | {PLAIN_NAMES.get(m, m)} | {acc_m:.2f} ± {acc_s:.2f} | {int(ing_m)}/{tot_noisy} | {noise_m:.1f}% | {comp_m:.1f}% | {time_m:.1f}s |"
            )

    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    logger.info("Saved Markdown Summary to %s", out_file)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate summary tables for ALG paper.")
    parser.add_argument("--input-dir", default="results/experiments/paper_benchmark", help="Directory with run JSONs.")
    parser.add_argument("--output-dir", default="research/tables", help="Output directory for generated tables.")
    args = parser.parse_args()

    in_dir = Path(args.input_dir)
    out_dir = Path(args.output_dir)

    grouped = load_results(in_dir)
    if not grouped:
        logger.warning("No JSON run files found in %s", in_dir)
        return

    generate_latex_table1(grouped, out_dir / "table1_main_benchmark.tex")
    generate_latex_table2(grouped, out_dir / "table2_ablation_study.tex")
    generate_markdown_summary(grouped, out_dir / "summary_table.md")


if __name__ == "__main__":
    main()

